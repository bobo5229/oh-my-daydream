import { test, expect } from '@playwright/test';
import { loadLore } from '../src/metadata/lore.ts';
import { NOVEL_PROGRESS_KEY } from '../src/client/storage.ts';

test('S05-T03：Lore 分类、正式名和别称搜索可用，空结果明确且资料页签支持键盘', async ({ page }) => {
  await page.goto('/read/ch03/');
  await page.getByRole('button', { name: '打开资料抽屉' }).click();
  const tab = page.getByRole('tab', { name: '行业编年', exact: true });
  await tab.focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: 'Lore', exact: true })).toBeFocused();
  await page.getByLabel('搜索 Lore').fill('探微');
  await expect(page.locator('[data-entity-result]:visible')).toHaveCount(1);
  await expect(page.locator('[data-entity-result]:visible')).toContainText('深圳探微');
  await page.getByLabel('资料类别').selectOption('harness');
  await expect(page.locator('[data-lore-empty]')).toBeVisible();
  await page.getByLabel('搜索 Lore').fill('Kybernetes');
  await expect(page.locator('[data-entity-result]:visible')).toHaveCount(1);
  await expect(page.locator('[data-entity-result]:visible')).toContainText('Harness');
  await page.getByLabel('搜索 Lore').fill('没有这个条目');
  await expect(page.locator('[data-lore-empty]')).toBeVisible();
});

test('S05-T05：完整原资料可展开并恢复，搜索条件与正文进度不被资料阅读覆盖', async ({ page }) => {
  const lore = await loadLore();
  const source = lore.sources.find(source => source.id === 'epistemic')!;
  await page.goto('/read/ch03/');
  await expect(page.locator('article')).toHaveAttribute('data-current-anchor', /r-ch03/);
  await page.evaluate(() => scrollTo(0, 1000));
  await expect.poll(() => page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}').scrollFraction > 0, NOVEL_PROGRESS_KEY)).toBe(true);
  await page.getByRole('button', { name: '打开资料抽屉' }).click();
  await page.getByRole('tab', { name: 'Lore', exact: true }).click();
  await page.getByLabel('搜索 Lore').fill('Kybernetes');
  await page.locator('[data-open-entity="kybernetes"]').click();
  await page.locator('[data-lore-full] > summary').click();
  const normalize = (value: string) => value.replace(/\s/g, '');
  expect(normalize(await page.locator('[data-lore-source="epistemic"]').textContent() ?? '')).toBe(normalize(source.text));
  await page.getByRole('button', { name: '展开完整资料独立阅读' }).click();
  await expect(page.locator('#expanded-reader [data-lore-source="epistemic"]')).toBeVisible();
  expect(await page.evaluate(() => scrollY)).toBe(1000);
  await page.keyboard.press('Escape');
  await expect(page.locator('#resources-drawer [data-lore-source="epistemic"]')).toBeVisible();
  await page.getByRole('button', { name: '返回列表', exact: true }).click();
  await expect(page.getByLabel('搜索 Lore')).toHaveValue('Kybernetes');
  await page.getByRole('button', { name: '关闭资料抽屉' }).click();
  const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}'), NOVEL_PROGRESS_KEY);
  await page.goto('/lore/kybernetes/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Kybernetes');
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key) ?? '{}').anchorId, NOVEL_PROGRESS_KEY)).toBe(saved.anchorId);
  await page.getByRole('link', { name: '返回正文原位置', exact: true }).click();
  await expect(page.locator('article')).toHaveAttribute('data-current-anchor', saved.anchorId);
});

test('S05-T04：上下文章节列表会更新，摘要有来源，相关条目及返回列表保留搜索状态和正文位置', async ({ page }) => {
  await page.goto('/read/ch05/');
  await expect(page.locator('article')).toHaveAttribute('data-current-anchor', /r-ch05/);
  await page.evaluate(() => scrollTo(0, 1000));
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(1000);
  await page.getByRole('button', { name: '打开资料抽屉' }).click();
  await page.getByRole('tab', { name: 'Lore', exact: true }).click();
  await expect(page.locator('[data-entity-result="atlas-iv"]')).toBeVisible();
  await page.getByLabel('搜索 Lore').fill('Kybernetes');
  await page.locator('[data-open-entity="kybernetes"]').click();
  await expect(page.locator('[data-entity-title]')).toHaveText('Kybernetes');
  await expect(page.locator('[data-entity-type]')).toHaveText('Harness');
  await expect(page.locator('[data-entity-source]')).toContainText('lore.md');
  await page.locator('[data-related-entity="epistemic"]').click();
  await expect(page.locator('[data-entity-type]')).toHaveText('企业');
  await page.getByRole('button', { name: '返回上一条目' }).click();
  await expect(page.locator('[data-entity-title]')).toHaveText('Kybernetes');
  await page.getByRole('button', { name: '返回列表', exact: true }).click();
  await expect(page.getByLabel('搜索 Lore')).toHaveValue('Kybernetes');
  await page.getByRole('button', { name: '关闭资料抽屉' }).click();
  expect(await page.evaluate(() => scrollY)).toBe(1000);
  await page.goto('/read/ch01/');
  await page.getByRole('button', { name: '打开资料抽屉' }).click();
  await page.getByRole('tab', { name: 'Lore', exact: true }).click();
  await expect(page.locator('[data-entity-result="atlas-iv"]')).not.toBeVisible();
});
